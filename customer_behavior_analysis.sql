REVENUE GENERATED BY MALE AND FEMALE CUSTOMERS

SELECT
gender,
SUM(purchase_amount) AS total_revenue
FROM customer
GROUP BY gender;

CUSTOMERS WHO USED DISCOUNT AND SPENT
-- MORE THAN OR EQUAL TO THE AVERAGE PURCHASE AMOUNT

SELECT
customer_id,
purchase_amount
FROM customer
WHERE discount_applied = 'Yes'
AND purchase_amount >= (
SELECT AVG(purchase_amount)
FROM customer
);

TOP 5 PRODUCTS WITH HIGHEST AVERAGE REVIEW RATING

SELECT
item_purchased,
ROUND(AVG(review_rating::numeric), 2) AS average_product_rating
FROM customer
GROUP BY item_purchased
ORDER BY average_product_rating DESC
LIMIT 5;

AVERAGE PURCHASE AMOUNT: STANDARD VS EXPRESS SHIPPING

SELECT
shipping_type,
ROUND(AVG(purchase_amount), 2) AS average_purchase_amount
FROM customer
WHERE shipping_type IN ('Standard', 'Express')
GROUP BY shipping_type;

DO SUBSCRIBED CUSTOMERS SPEND MORE?

SELECT
subscription_status,
COUNT(customer_id) AS total_customers,
ROUND(AVG(purchase_amount), 2) AS average_spend,
SUM(purchase_amount) AS total_revenue
FROM customer
GROUP BY subscription_status
ORDER BY total_revenue DESC;

TOP 5 PRODUCTS WITH HIGHEST DISCOUNT RATE

SELECT
item_purchased,
ROUND(
SUM(
CASE
WHEN discount_applied = 'Yes' THEN 1
ELSE 0
END
)::numeric / COUNT(*) * 100, 2
) AS discount_rate
FROM customer
GROUP BY item_purchased
ORDER BY discount_rate DESC
LIMIT 5;

